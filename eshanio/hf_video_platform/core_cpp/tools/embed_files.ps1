# embed_files.ps1
# frontend/index.html dosyasini C++ embedded_frontend.h headerina donusturur
# CMake tarafindan build oncesi otomatik calistirilir

param(
    [string]$InputFile  = "$PSScriptRoot\..\..\frontend\index.html",
    [string]$OutputFile = "$PSScriptRoot\..\src\embedded\embedded_frontend.h"
)

$outDir = Split-Path $OutputFile
if (!(Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }

$content = [System.IO.File]::ReadAllBytes($InputFile)

$sb = [System.Text.StringBuilder]::new()
$null = $sb.AppendLine("// AUTO-GENERATED - DO NOT EDIT")
$null = $sb.AppendLine("// Generated by tools/embed_files.ps1")
$null = $sb.AppendLine("#pragma once")
$null = $sb.AppendLine("#include <cstddef>")
$null = $sb.AppendLine("")
$null = $sb.AppendLine("namespace embedded {")
$null = $sb.AppendLine("")
$null = $sb.AppendLine("// frontend/index.html")
$null = $sb.Append("inline const unsigned char index_html[] = {")

for ($i = 0; $i -lt $content.Length; $i++) {
    if ($i % 16 -eq 0) { $null = $sb.AppendLine(""); $null = $sb.Append("    ") }
    $null = $sb.Append("0x" + $content[$i].ToString("x2") + ",")
    if (($i % 16) -ne 15) { $null = $sb.Append(" ") }
}

$null = $sb.AppendLine("")
$null = $sb.AppendLine("};")
$null = $sb.AppendLine("inline const size_t index_html_len = $($content.Length);")
$null = $sb.AppendLine("")
$null = $sb.AppendLine("} // namespace embedded")

[System.IO.File]::WriteAllText($OutputFile, $sb.ToString())
Write-Host "Embedded: $InputFile -> $OutputFile ($($content.Length) bytes)"
